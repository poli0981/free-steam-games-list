/**
 * After `vite build`, turn the admin build output into a TypeScript module the
 * Worker imports: worker/generated/admin-bundle.ts.
 *
 * Why a generated module rather than static assets or wrangler Text rules:
 *
 *   - dist/ is served to ANYONE by the asset server, and it is also Tauri's
 *     frontendDist and the service worker's precache source. The admin must be
 *     in none of those.
 *   - A plain .ts module is understood identically by tsc, Vitest and
 *     wrangler's bundler. Text-module rules would type one way and bundle
 *     another.
 *
 * The shell's single module script gets a nonce placeholder, which
 * worker/routes/admin-spa.ts replaces per response. The checks below fail the
 * build if the output ever stops fitting that model (a second script, an
 * inline script, code splitting, a runaway size).
 *
 * `writeBundle`, reading the bundle Vite hands it - NOT `closeBundle` reading
 * the output directory. closeBundle also runs when the build has FAILED (Vite
 * closes the bundle in a `finally`), so on a clean checkout it threw ENOENT for
 * the missing index.html and that replaced the build's real error in the log.
 * And on a machine with an earlier build, reading the directory could pick up
 * that earlier build's files.
 */
import { createHash } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, extname } from "node:path";
import type { Plugin } from "vite";

const TEXT = new Map([
  [".js", "text/javascript; charset=utf-8"],
  [".css", "text/css; charset=utf-8"],
  [".svg", "image/svg+xml"],
  [".json", "application/json; charset=utf-8"],
]);
const BINARY = new Map([
  [".woff2", "font/woff2"],
  [".woff", "font/woff"],
  [".png", "image/png"],
  [".webp", "image/webp"],
]);

/** The Worker's admin bundle, embedded in its script: keep it modest. */
const MAX_TOTAL_BYTES = 1.5 * 1024 * 1024;
const PLACEHOLDER = "__ADMIN_NONCE__";

export function emitWorkerBundle(options: { target: string }): Plugin {
  return {
    name: "f2p-admin-worker-bundle",
    apply: "build",
    writeBundle(_output, bundle) {
      const html = bundle["index.html"];
      if (!html || html.type !== "asset") throw new Error("admin bundle: the build emitted no index.html");
      let shell = typeof html.source === "string" ? html.source : Buffer.from(html.source).toString("utf-8");

      const scripts = [...shell.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/g)];
      if (scripts.length !== 1) {
        throw new Error(`admin bundle: expected exactly one <script> in the shell, found ${scripts.length}`);
      }
      const [tag, inline] = [scripts[0][0], scripts[0][1]];
      if (inline.trim()) throw new Error("admin bundle: the shell's script must be external, not inline");
      if (!/type="module"/.test(tag) || !/src="\/admin\/assets\/[^"]+\.js"/.test(tag)) {
        throw new Error(`admin bundle: unexpected script tag ${tag}`);
      }
      shell = shell.replace(tag, tag.replace("<script", `<script nonce="${PLACEHOLDER}"`));

      const assets: Record<string, { contentType: string; encoding: "utf8" | "base64"; body: string }> = {};
      let total = Buffer.byteLength(shell);
      let scriptsOut = 0;
      for (const [fileName, output] of Object.entries(bundle)) {
        if (fileName === "index.html") continue;
        if (!fileName.startsWith("assets/")) throw new Error(`admin bundle: unexpected output ${fileName}`);
        const ext = extname(fileName);
        const key = `/admin/${fileName}`;
        const bytes =
          output.type === "chunk"
            ? Buffer.from(output.code, "utf-8")
            : typeof output.source === "string"
              ? Buffer.from(output.source, "utf-8")
              : Buffer.from(output.source);
        total += bytes.length;
        if (ext === ".js") scriptsOut += 1;
        if (TEXT.has(ext)) {
          assets[key] = { contentType: TEXT.get(ext)!, encoding: "utf8", body: bytes.toString("utf-8") };
        } else if (BINARY.has(ext)) {
          assets[key] = { contentType: BINARY.get(ext)!, encoding: "base64", body: bytes.toString("base64") };
        } else {
          throw new Error(`admin bundle: no content type for ${key}`);
        }
      }
      if (scriptsOut !== 1) {
        throw new Error(`admin bundle: expected one JS file (codeSplitting off), found ${scriptsOut}`);
      }
      if (total > MAX_TOTAL_BYTES) {
        throw new Error(`admin bundle: ${total} bytes exceeds the ${MAX_TOTAL_BYTES}-byte budget`);
      }

      const buildId = createHash("sha256")
        .update(shell)
        .update(Object.keys(assets).sort().join("\n"))
        .digest("hex")
        .slice(0, 12);

      mkdirSync(dirname(options.target), { recursive: true });
      writeFileSync(
        options.target,
        "// GENERATED by admin/build/emit-worker-bundle.ts during `npm run build:admin`.\n" +
          "// Do not edit and do not commit (it is gitignored): it is rebuilt from admin/ every time.\n" +
          'import type { AdminBundle } from "../lib/admin-bundle";\n\n' +
          `export const ADMIN_BUNDLE: AdminBundle = ${JSON.stringify({ buildId, shell, assets })};\n`,
        "utf-8",
      );
      this.info?.(`admin bundle ${buildId}: ${Object.keys(assets).length} assets, ${(total / 1024).toFixed(0)} KiB`);
    },
  };
}
